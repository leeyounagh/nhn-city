// 흥정 폴백 데이터 — LLM 없이도 흥정이 성립하도록 키워드 분류 + 카테고리별 변형 대사를 제공한다.
import type { HaggleCategory } from "@/types/game";
import type { Persona } from "./personas";
import { variant } from "./pick";

const CATEGORIES: HaggleCategory[] = [
  "flattery",
  "logic",
  "bulk",
  "sob",
  "threat",
  "smalltalk",
  "quality",
];

export function isValidCategory(c: unknown): c is HaggleCategory {
  return typeof c === "string" && (CATEGORIES as string[]).includes(c);
}

// 키워드 기반 폴백 분류 (LLM 없이도 흥정이 성립하게).
export function fallbackCategory(utterance: string): HaggleCategory {
  const u = utterance.toLowerCase();
  const has = (...ks: string[]) => ks.some((k) => u.includes(k));
  if (has("죽여", "가만", "협박", "후회", "칼", "손봐", "박살", "때려", "패버", "소문", "나쁘게", "험한 꼴", "본때", "혼내", "재미없", "각오", "가만두", "혼쭐", "골로")) return "threat";
  if (has("흠집", "금 갔", "금갔", "품질", "상태 안", "낡", "깨졌", "결함", "긁", "때가", "먼지", "중고", "하자", "얼룩", "옹이", "갈라", "쪼개", "휘었", "뒤틀", "벌레", "썩", "구멍", "트집", "티가", "질 나", "질이 나")) return "quality";
  if (
    /\d+\s*(개|점|묶음|박스|자루|다발|채|장)/.test(u) ||
    /(한|두|세|네|다섯|여섯|일곱|여덟|아홉|열|스무|스물|서른|수십|수백)\s*(개|점|묶음|자루|다발|채|장)/.test(u) ||
    has("많이", "전부", "대량", "다 살", "다살", "여러", "여럿", "묶어", "한꺼번", "잔뜩", "왕창", "몽땅", "박스", "도매", "떨이")
  )
    return "bulk";
  if (has("불쌍", "사정", "도와", "굶", "제발", "형편", "아이", "가족", "돈이 없", "빠듯", "겨우", "재건", "폐허", "부탁", "간절", "어렵", "힘든", "힘들", "살려", "눈물")) return "sob";
  if (has("멋지", "대단", "훌륭", "최고", "솜씨", "명성", "존경", "귀한", "역시", "장인", "실력", "명장", "물건 좋", "좋은 물건", "안목", "눈썰미", "대인")) return "flattery";
  if (has("시세", "시가", "계산", "합리", "따져", "값어치", "비싸", "비싼", "바가지", "깎", "할인", "에누리", "적정", "원가", "너무 비", "싸던데", "싸네", "싸게 파", "다른 데", "다른 마을", "다른 곳", "딴 데", "타 마을", "이보다")) return "logic";
  return "smalltalk";
}

