export function fallbackLine(
  category: HaggleCategory,
  persona: Persona,
  seed = 0,
  turnsLeft = 0,
): string {
  const lines = FALLBACK_LINES[category];
  if (!lines) return persona.greeting;
  return variant(lines, seed + turnsLeft);
}
